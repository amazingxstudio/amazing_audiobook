const KEY = 'ab.lang';
let lang = 'mm';

/** Translate. Missing key in the current language -> English text -> (last resort) the key itself, never blank. */
export function t(key, args) {
  let s = I18N[lang]?.[key];
  if (s === undefined || s === '') s = I18N.en[key];
  if (s === undefined) s = key;
  return args ? s.replace(/\{(\w+)\}/g, (m, k) => (args[k] !== undefined ? String(args[k]) : m)) : s;
}
export const getLang = () => lang;

/** Set an element's text from a key; the key (and args) are remembered so a language switch re-translates it. */
export function setT(el, key, args) {
  el.dataset.i18n = key;
  if (args) el.dataset.i18nArgs = JSON.stringify(args); else delete el.dataset.i18nArgs;
  el.textContent = t(key, args);
}
export function setAria(el, key, args) {
  el.dataset.i18nAria = key;
  if (args) el.dataset.i18nArgs = JSON.stringify(args);
  el.setAttribute('aria-label', t(key, args));
}

/** Re-translate everything under root. Only text/attributes change: no re-render, so inputs, scroll and jobs are untouched. */
export function applyI18n(root = document) {
  const q = '[data-i18n],[data-i18n-aria],[data-i18n-placeholder],[data-i18n-title]';
  for (const el of root.querySelectorAll(q)) {
    let args; try { args = el.dataset.i18nArgs ? JSON.parse(el.dataset.i18nArgs) : undefined; } catch { args = undefined; }
    if (el.dataset.i18n) el.textContent = t(el.dataset.i18n, args);
    if (el.dataset.i18nAria) el.setAttribute('aria-label', t(el.dataset.i18nAria, args));
    if (el.dataset.i18nPlaceholder) el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder, args));
    if (el.dataset.i18nTitle) el.setAttribute('title', t(el.dataset.i18nTitle, args));
  }
}

export function setLang(l, { save = true } = {}) {
  lang = l === 'en' ? 'en' : 'mm';
  if (save) { try { localStorage.setItem(KEY, lang); } catch { /* ignore */ } }
  document.documentElement.lang = lang === 'mm' ? 'my' : 'en';
  document.title = t('app_title');
  applyI18n(document);
  document.querySelectorAll('[data-lang]').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
}
export function initLang() {
  let l = 'mm';
  try { l = localStorage.getItem(KEY) || 'mm'; } catch { /* ignore */ }
  setLang(l, { save: false });
}
